class Translator:
    def __init__(self, language='es'):
        self.current_language = language
    
    def set_language(self, language):
        if language in TRANSLATIONS:
            self.current_language = language
    
    def translate(self, key, **kwargs):
        """
        Obtiene la traducción de una clave en el idioma actual.
        Soporta interpolación de variables con formato {variable}
        """
        if self.current_language not in TRANSLATIONS:
            self.current_language = 'es'
        
        translations_dict = TRANSLATIONS[self.current_language]
        text = translations_dict.get(key, f"[{key}]")
        
        # Interpolación de variables
        if kwargs:
            try:
                text = text.format(**kwargs)
            except KeyError:
                pass  # Si una variable no está disponible, dejar el placeholder
        
        return text
    
    def get_available_languages(self):
        """Retorna una lista de idiomas disponibles"""
        return list(TRANSLATIONS.keys())
    
    def get_language_names(self):
        """Retorna un diccionario con código de idioma -> nombre legible"""
        return {
            'es': 'Español',
            'en': 'English',
            'pt': 'Português',
            'id': 'Bahasa Indonesia',
            'vi': 'Tiếng Việt',
            'fr': 'Français'
        }

# Crear instancia global
_translator = Translator('es')

def _(key, **kwargs):
    """Función global de traducción. Uso: _('title')"""
    return _translator.translate(key, **kwargs)

def set_language(language):
    """Cambiar idioma global"""
    _translator.set_language(language)

def get_translator():
    """Obtener la instancia del traductor"""
    return _translator
